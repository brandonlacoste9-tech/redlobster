// Language labels for the dropdown
const LANG_LABELS = {
    en: '🇬🇧 EN',
    fr: '🇨🇦 FR',
    es: '🇪🇸 ES',
    pt: '🇧🇷 PT',
    ar: '🇦🇷 AR',
};

// Apply translations to the page
function applyLanguage(lang) {
    const t = TRANSLATIONS[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            el.innerHTML = t[key];
        }
    });

    // Save preference
    localStorage.setItem('openclaw-lang', lang);

    // Update dropdown display
    const currentBtn = document.getElementById('langCurrent');
    if (currentBtn) currentBtn.textContent = LANG_LABELS[lang];
}

// Initialize language on load
function initLanguage() {
    const saved = localStorage.getItem('openclaw-lang') || 'en';
    applyLanguage(saved);
}
