const LANG_LABELS = {
    en: '🇬🇧 EN',
    fr: '🌍 FR',
    es: '🇲🇽 ES',
    pt: '🇧🇷 PT',
    hi: '🇮🇳 HI'
};

function applyLanguage(lang) {
    const t = TRANSLATIONS[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            el.innerHTML = t[key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.placeholder = t[key].replace(/<[^>]*>?/gm, ''); // Remove tags for placeholder
        }
    });

    localStorage.setItem('openclaw-lang', lang);
    const currentBtn = document.getElementById('langCurrent');
    if (currentBtn) currentBtn.textContent = LANG_LABELS[lang];
    
    // Set HTML lang attribute
    document.documentElement.lang = lang === 'fr' ? 'fr-CA' : (lang === 'en' ? 'en-CA' : lang);
}

function initLanguage() {
    // Default to French for Canada Sovereign experience if not set
    const saved = localStorage.getItem('openclaw-lang') || 'fr'; 
    applyLanguage(saved);
}

document.addEventListener('DOMContentLoaded', () => {
    initLanguage();
});
